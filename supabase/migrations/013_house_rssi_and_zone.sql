-- 1) เก็บความแรงสัญญาณ WiFi ของบอร์ด (RSSI) ไว้โชว์บนแถบสถานะ
-- 2) เปลี่ยนโซนทองของ house-01 เป็น 30-33°C (Beer สั่ง 9 ส.ค.)
--
-- ⚠️ ข้อ 2 เป็นการ "แก้ข้อมูลเดิม" ใน control_config — ปกติต้องขออนุญาตก่อนตามนโยบายในCLAUDE.md
--    ครั้งนี้ Beer สั่งเองโดยตรง · ปลอดภัย: temp_fruit_min/max เป็นค่า "แสดงผล" ล้วนๆ
--    เฟิร์มแวร์ไม่ได้อ่าน 2 key นี้เลย (grep temp_fruit ใน firmware/ = ไม่เจอ)
--    ตัวคุมจริงคือ temp_heater_on / temp_heater_off / temp_exhaust_on ซึ่งไม่ถูกแตะในไฟล์นี้
--
-- idempotent — รันซ้ำได้
