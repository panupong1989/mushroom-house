-- ----------------------------------------------------------------------------
-- 1) houses.last_rssi — ESP32 PATCH ค่านี้มาพร้อม last_mode ทุกครั้งที่โพสต์ readings (~20 วิ)
--    หน่วย dBm (ติดลบ; ใกล้ 0 = แรง) เช่น -55 ดีมาก, -67 พอใช้, -80 อ่อน
--    null = ยังไม่เคยรายงาน (เฟิร์มแวร์รุ่นเก่าที่ยังไม่ push)
-- ----------------------------------------------------------------------------

alter table houses add column if not exists last_rssi smallint;

comment on column houses.last_rssi is
  'ความแรงสัญญาณ WiFi ที่ ESP32 รับได้ (dBm, ติดลบ — ใกล้ 0 = แรง) · null = เฟิร์มแวร์ยังไม่ push';

-- ----------------------------------------------------------------------------
-- 2) โซนทอง (ช่วงอุณหภูมิเป้าหมายตอนออกดอก) 28-32 -> 30-33 สำหรับ house-01
--    เขียนเฉพาะ profile ที่มี key นี้อยู่แล้ว (ไม่สร้าง row ใหม่)
-- ----------------------------------------------------------------------------

update control_config set value = 30 where house_id = 'house-01' and key = 'temp_fruit_min';
update control_config set value = 33 where house_id = 'house-01' and key = 'temp_fruit_max';
