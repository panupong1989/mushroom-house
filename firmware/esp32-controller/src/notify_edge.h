#pragma once
#include <stdint.h>

// ---- ตัวตรวจ "ขอบขาขึ้น" ของการแจ้งเตือน พร้อม hysteresis + cooldown ----
// ⚠️ ตรรกะล้วน ไม่แตะฮาร์ดแวร์/ไม่ใช่ safety — คุมแค่ "โพสต์ alert ตอนไหน"
//    interlock (ตัดปั๊ม/heater/mist) อยู่ที่ safety.cpp เหมือนเดิม ไม่เกี่ยวกับไฟล์นี้
// แยกไฟล์ออกมาเพื่อ unit test บน host ได้ (pio test -e native)
//
// ปัญหาที่แก้ (10 ส.ค. 69): ของเดิมใน main.cpp เช็คแค่ "cond จริง/เท็จ" — ค่าตกใต้เกณฑ์
// รอบเดียว (control loop 2 วิ) ก็รีเซ็ตขอบแล้วโพสต์ใหม่ทันทีที่ขึ้นมาอีก
// ผลจริง: HOT ยิง 3 แถวใน 36 วิ ตอนอุณหภูมิเด้ง 32.9 <-> 33.0 ที่เกณฑ์ 33.0
//        (RH_HIGH เคยยิง 18 ครั้งใน 12 นาที) -> LINE เด้งรัว

struct AlertEdge {
  bool     active       = false;  // อยู่ในสถานะ "เกินเกณฑ์" อยู่ (ยังไม่กลับเข้าเขตปลอดภัย)
  bool     posted       = false;  // เคยโพสต์ code นี้ไปแล้วอย่างน้อยครั้งหนึ่ง (นับตั้งแต่บูต)
  uint32_t last_post_ms = 0;      // millis() ตอนโพสต์ครั้งล่าสุด
};

// อัปเดตสถานะ 1 ชนิดแจ้งเตือน — คืน true = "ควรโพสต์ alert รอบนี้"
//
//   set_cond   = ข้ามเกณฑ์แล้ว (เช่น t >= 33.0)
//   clear_cond = กลับเข้าเขตปลอดภัย "เกิน hysteresis" แล้ว (เช่น t < 32.5)
//   repost_ms  = เว้นระยะขั้นต่ำก่อนโพสต์ code เดิมซ้ำ (0 = ไม่เว้น)
//
// ทั้ง set/clear เป็น false = อยู่ในแถบ hysteresis หรือค่าอ่านไม่ได้ (NAN) -> คงสถานะเดิม
// ไม่โพสต์ ไม่รีเซ็ต (ของเดิม NAN = รีเซ็ตขอบ ทำให้พออ่านได้อีกก็ยิงซ้ำ)
bool alert_edge_update(AlertEdge &e, bool set_cond, bool clear_cond, uint32_t now_ms, uint32_t repost_ms);
